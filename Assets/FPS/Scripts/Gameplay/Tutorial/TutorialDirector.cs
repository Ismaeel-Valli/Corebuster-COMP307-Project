using System;
using System.Collections.Generic;
using Unity.FPS.Game;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Unity.FPS.Gameplay
{
    /// <summary>
    /// Runs the emergency officer's wake-up in the tutorial wing (corebuster_tutorial_001). The player is revived beside
    /// their hibernation pod unarmed, hurt and with two cores banked in the Disassembler; stretches (look, move, crouch,
    /// jump); takes their sidearm from the locker (which unseals the quarters); walks the fabrication gallery; drills on
    /// the dormant targets at the far end (fire, aim, break the armour, Core Bust, Disassembler, Core Bust the Elite);
    /// collects the black keycard at the clearance terminal and taps it on the exit's reader.
    /// The armour is taught passively, by the hologram over the target and a line from ship systems on the first hit.
    /// Steps advance on what the player has actually done, so doing things early or out of order never stalls it.
    /// The HUD reads the card (title, tasks) and the transmission line from here.
    /// </summary>
    public class TutorialDirector : MonoBehaviour
    {
        public enum Step
        {
            Inactive, WakeUp, Stretch, ArmUp, Gallery, Drill, CoreBust, Disassembler, EliteBust, Clearance, Keycard,
            Complete,
        }

        [Serializable]
        public class Reveal
        {
            [Tooltip("Shown from the start of this step (hidden before it).")]
            public Step From;
            public GameObject[] Objects;
        }

        /// <summary>A line from ship systems: the subtitle, and the voice that speaks it (optional).</summary>
        [Serializable]
        public class VoiceLine
        {
            [TextArea] public string Text;
            public AudioClip Voice;
            [Tooltip("Subtitle time when there is no voice; a voiced line holds for its clip.")]
            public float Seconds = 4f;
        }

        public class Task
        {
            public string Key;
            public string Text;
            public bool Done;
        }

        [Header("Wing")]
        [Tooltip("The wing's floor area. The tutorial only runs when the player starts inside it.")]
        public Bounds WingBounds = new Bounds(new Vector3(-246f, 5f, -21f), new Vector3(31f, 12f, 43f));
        public HibernationPod Pod;
        public WeaponLocker Locker;
        public SecurityDoor QuartersDoor;

        [Header("Drill")]
        [Tooltip("Entering this sphere starts the combat drill.")]
        public Transform DrillPoint;
        public float DrillRadius = 12f;
        [Tooltip("The unarmoured exhibit; it stays invulnerable.")]
        public Health ShowcaseRobot;
        public CoreExecutionTarget Armoured;
        public CoreExecutionTarget Elite;
        [Tooltip("Lowest health the player is revived with.")]
        public float MinStartHealth = 20f;
        [Tooltip("Cores already banked in the Disassembler.")]
        [Min(0)] public int StartCharge = 2;

        [Header("Exit")]
        public KeycardDispenser Terminal;
        public KeycardAccessPoint ExitReader;
        public SecurityDoor ExitDoor;

        [Header("Staging")]
        public Reveal[] Reveals;

        [Header("Wake-up")]
        [Tooltip("Seconds of black before the eyes open.")]
        public float WakeDelay = .8f;
        [Tooltip("Seconds the player is held still while they come round.")]
        public float WakeHold = 3.2f;

        [Tooltip("The ship AI's status report as the officer comes round. Voiced lines are never cut off by the next " +
                 "step; generated by Tools/Art/generate_ship_ai_voice.py.")]
        public VoiceLine[] WakeUpLines =
        {
            new VoiceLine { Text = "Emergency officer, revival complete.", Seconds = 3f },
            new VoiceLine { Text = "Warning. Hostile units detected aboard the ship.", Seconds = 4f },
            new VoiceLine { Text = "Life support systems are stable.", Seconds = 3f },
            new VoiceLine { Text = "Main power is offline. Backup generators are running.", Seconds = 4.5f },
            new VoiceLine { Text = "Your vitals are weak. Stretch it out, and get the blood moving.", Seconds = 4.5f },
        };

        [Header("Sound")]
        public AudioClip TaskDoneSfx;
        public AudioClip TransmissionSfx;
        public AudioClip StepSfx;
        [Range(0f, 1f)] public float SfxVolume = .7f;
        [Range(0f, 1f)] public float VoiceVolume = 1f;

        public const string Speaker = "SHIP SYSTEMS";

        public Step Current { get; private set; } = Step.Inactive;
        public bool IsActive => Current != Step.Inactive;
        /// <summary>The card: a heading, a line under it and the tasks to tick off. Version bumps on every change.</summary>
        public string CardTitle { get; private set; }
        public string CardSubtitle { get; private set; }
        public IReadOnlyList<Task> Tasks => m_Tasks;
        public int CardVersion { get; private set; }
        public bool CardVisible { get; private set; }
        /// <summary>The transmission on air now, and since when (null when silent).</summary>
        public string Transmission { get; private set; }
        public float TransmissionStart { get; private set; }
        public float TransmissionDuration { get; private set; }
        /// <summary>1 while the eyes are shut, 0 once open (the HUD's eyelids).</summary>
        public float EyesClosed { get; private set; }

        readonly List<Task> m_Tasks = new List<Task>();
        readonly List<(string text, float seconds, AudioClip voice)> m_Lines = new List<(string, float, AudioClip)>();
        readonly List<WeaponController> m_HeldBackWeapons = new List<WeaponController>();

        PlayerCharacterController m_Character;
        PlayerWeaponsManager m_Weapons;
        PlayerInputHandler m_Input;
        CoreExecutioner m_Executioner;
        Disassembler m_Disassembler;
        Health m_Health;
        AudioSource m_Audio;
        AudioSource m_Voice;
        bool m_OnAirVoiced, m_VoicePaused;

        float m_StepTime;
        float m_StartTime;
        float m_LookTotal, m_MoveTotal, m_AimTime;
        float m_LastYaw, m_LastPitch;
        Vector3 m_LastPosition;
        bool m_Greeted, m_ArmourHinted, m_ArmouredDone, m_EliteDone, m_Fired;
        float m_DisassemblerFiredAt = -1f;
        float m_StepDoneAt = -1f;

        Task m_Look, m_Move, m_Crouch, m_Jump, m_Fire, m_Aim;

        void Awake()
        {
            m_Character = FindAnyObjectByType<PlayerCharacterController>();
            if (!m_Character || !WingBounds.Contains(m_Character.transform.position + Vector3.up))
            {
                enabled = false;
                return;
            }

            m_Weapons = m_Character.GetComponent<PlayerWeaponsManager>();
            m_Input = m_Character.GetComponent<PlayerInputHandler>();
            m_Executioner = m_Character.GetComponent<CoreExecutioner>();
            m_Disassembler = m_Character.GetComponent<Disassembler>();
            m_Health = m_Character.GetComponent<Health>();
            m_Audio = gameObject.AddComponent<AudioSource>();
            m_Audio.playOnAwake = false;
            m_Audio.spatialBlend = 0f;
            m_Voice = gameObject.AddComponent<AudioSource>();
            m_Voice.playOnAwake = false;
            m_Voice.spatialBlend = 0f;

            // Revived unarmed: the sidearm is in the locker. Runs before PlayerWeaponsManager.Start hands them out.
            if (m_Weapons)
            {
                m_HeldBackWeapons.AddRange(m_Weapons.StartingWeapons);
                m_Weapons.StartingWeapons.Clear();
            }
            Current = Step.WakeUp;
        }

        void Start()
        {
            if (!IsActive) return;
            m_StartTime = Time.time;
            EyesClosed = 1f;

            if (Locker)
            {
                if (!Locker.Weapon && m_HeldBackWeapons.Count > 0) Locker.Weapon = m_HeldBackWeapons[0];
                Locker.OnTaken += OnWeaponTaken;
            }
            if (m_Weapons) m_Weapons.OnAddedWeapon += OnWeaponAdded;
            if (m_Executioner) m_Executioner.OnExecutionFinished += OnExecuted;
            if (m_Disassembler)
            {
                m_Disassembler.AddCharge(StartCharge);
                m_Disassembler.OnFired += OnDisassemblerFired;
            }
            if (Terminal) Terminal.OnTaken += OnKeycardTaken;

            // The exhibits are for show: the unarmoured robot never goes down; the Elite only opens to the Disassembler.
            if (ShowcaseRobot) ShowcaseRobot.Invincible = true;
            if (Elite)
            {
                Elite.Health.Invincible = true;
                Elite.HoldForcedExposure = true;
            }
            if (Armoured)
            {
                Armoured.OnBecameVulnerable += OnArmourBroken;
                Armoured.Health.OnDamaged += OnArmouredHit;
            }

            if (QuartersDoor) QuartersDoor.Lock();
            ApplyReveals();
            StartCoroutine(SetStartHealth());

            // Held still with the eyes shut while they come round.
            m_Character.enabled = false;
        }

        void OnDestroy()
        {
            if (Locker) Locker.OnTaken -= OnWeaponTaken;
            if (m_Weapons) m_Weapons.OnAddedWeapon -= OnWeaponAdded;
            if (m_Executioner) m_Executioner.OnExecutionFinished -= OnExecuted;
            if (m_Disassembler) m_Disassembler.OnFired -= OnDisassemblerFired;
            if (Terminal) Terminal.OnTaken -= OnKeycardTaken;
            if (Armoured)
            {
                Armoured.OnBecameVulnerable -= OnArmourBroken;
                if (Armoured.Health) Armoured.Health.OnDamaged -= OnArmouredHit;
            }
        }

        // Health.Start fills the player up; this runs after it.
        System.Collections.IEnumerator SetStartHealth()
        {
            yield return null;
            if (!m_Health) yield break;
            float rewards = (Armoured ? Armoured.HealthReward : 0f) + (Elite ? Elite.HealthReward : 0f);
            m_Health.CurrentHealth = Mathf.Clamp(m_Health.MaxHealth - rewards, MinStartHealth, m_Health.MaxHealth);
        }

        // ------------------------------------------------------------------ steps

        void Update()
        {
            if (!IsActive) return;
            HoldVoiceWhilePaused();
            UpdateTransmission();

            switch (Current)
            {
                case Step.WakeUp: UpdateWakeUp(); break;
                case Step.Stretch: UpdateStretch(); break;
                case Step.Gallery:
                    if (InDrillZone()) GoTo(Step.Drill);
                    break;
                case Step.Drill: UpdateDrill(); break;
                case Step.Disassembler: UpdateDisassembler(); break;
                case Step.Keycard:
                    if (ExitDoor && !ExitDoor.IsLocked) GoTo(Step.Complete);
                    break;
                case Step.Complete:
                    if (CardVisible && (Time.time - m_StepTime > 9f || !WingBounds.Contains(m_Character.transform.position)))
                        HideCard();
                    break;
            }
        }

        // Eyes shut (1) to open (0), seconds after WakeDelay: a heavy half-open, a slow blink, then open.
        static readonly AnimationCurve k_Eyelids = new AnimationCurve(
            new Keyframe(0f, 1f), new Keyframe(.55f, .5f), new Keyframe(.85f, .97f), new Keyframe(1.45f, .2f),
            new Keyframe(1.7f, .55f), new Keyframe(2.3f, 0f));

        void UpdateWakeUp()
        {
            float t = Time.time - m_StartTime;
            EyesClosed = Mathf.Clamp01(k_Eyelids.Evaluate(Mathf.Max(0f, t - WakeDelay)));
            if (t > .3f && Pod && !Pod.IsOpen) Pod.Open();
            if (t > WakeDelay + .4f && !m_Greeted)
            {
                m_Greeted = true;
                foreach (var line in WakeUpLines)
                    if (line != null && !string.IsNullOrEmpty(line.Text)) Say(line.Text, line.Seconds, line.Voice);
            }
            if (t < WakeHold) return;
            EyesClosed = 0f;
            m_Character.enabled = true;
            GoTo(Step.Stretch);
        }

        void UpdateStretch()
        {
            Transform body = m_Character.transform;
            float yaw = body.eulerAngles.y, pitch = m_Character.CameraVerticalAngle;
            m_LookTotal += Mathf.Abs(Mathf.DeltaAngle(m_LastYaw, yaw)) + Mathf.Abs(pitch - m_LastPitch);
            m_LastYaw = yaw;
            m_LastPitch = pitch;
            Vector3 step = Vector3.ProjectOnPlane(body.position - m_LastPosition, Vector3.up);
            if (step.magnitude < 1.5f && m_Character.IsGrounded) m_MoveTotal += step.magnitude;
            m_LastPosition = body.position;

            Tick(m_Look, m_LookTotal > 100f);
            Tick(m_Move, m_MoveTotal > 3.5f);
            Tick(m_Crouch, m_Character.IsCrouching);
            Tick(m_Jump, m_Character.HasJumpedThisFrame || (!m_Character.IsGrounded && m_Character.CharacterVelocity.y > 1.5f));

            if (!AllDone()) return;
            if (m_StepDoneAt < 0f) m_StepDoneAt = Time.time;
            if (Time.time - m_StepDoneAt > .9f) GoTo(Locker && Locker.IsTaken ? Step.Gallery : Step.ArmUp);
        }

        void UpdateDrill()
        {
            if (m_Weapons && m_Weapons.IsAiming && m_Weapons.GetActiveWeapon()) m_AimTime += Time.deltaTime;
            Tick(m_Fire, m_Fired);
            Tick(m_Aim, m_AimTime > .35f);
            // Breaking the armour (OnArmourBroken) moves on; until then the card only asks to take it down.
        }

        void UpdateDisassembler()
        {
            if (!Elite) return;
            if (Elite.IsCoreExposed)
            {
                GoTo(Step.EliteBust);
                return;
            }
            // A miss would strand the drill: refund the shot once it has had time to land.
            if (m_DisassemblerFiredAt >= 0f && Time.time - m_DisassemblerFiredAt > 1.4f)
            {
                m_DisassemblerFiredAt = -1f;
                if (m_Disassembler && !m_Disassembler.IsCharged)
                    m_Disassembler.AddCharge(m_Disassembler.ExecutionsForFullCharge);
                Interject(("Missed. Recharging the Disassembler for the drill. Put it on the Elite.", 4f));
            }
            if (m_Disassembler && !m_Disassembler.IsCharged && !m_Disassembler.IsFiring && m_DisassemblerFiredAt < 0f)
                m_Disassembler.AddCharge(m_Disassembler.ExecutionsForFullCharge);
        }

        bool InDrillZone() =>
            DrillPoint && Vector3.Distance(m_Character.transform.position, DrillPoint.position) < DrillRadius;

        void GoTo(Step step)
        {
            if (Current == step) return;
            Current = step;
            // A new step owns the subtitles: older chatter is dropped (the wake-up lines run on into the stretches).
            // Spoken lines are never cut off mid-sentence; the new step's lines queue behind them.
            if (step != Step.Stretch)
            {
                m_Lines.RemoveAll(line => !line.voice);
                if (!m_OnAirVoiced) Transmission = null;
            }
            m_StepTime = Time.time;
            m_StepDoneAt = -1f;
            ApplyReveals();
            if (step != Step.Stretch && step != Step.WakeUp) Play(StepSfx);

            switch (step)
            {
                case Step.Stretch:
                    m_LastYaw = m_Character.transform.eulerAngles.y;
                    m_LastPitch = m_Character.CameraVerticalAngle;
                    m_LastPosition = m_Character.transform.position;
                    SetCard("WAKE-UP ROUTINE", "Stretch out the hibernation stiffness");
                    m_Look = AddTask(Key("Player/Look", "MOUSE", true), "Look around");
                    m_Move = AddTask(MoveKeys(), "Walk it off");
                    m_Crouch = AddTask(Key("Player/Slide", "CTRL"), "Crouch");
                    m_Jump = AddTask(Key("Player/Jump", "SPACE"), "Jump");
                    break;

                case Step.ArmUp:
                    SetCard("ARM YOURSELF", "Your sidearm is in the locker ahead");
                    AddTask("HOLD " + Key("Player/Interact", "E"), "Take the blaster off its rack");
                    Say($"Your sidearm is in the locker ahead. {Key("Player/Interact", "E")} works the ship's panels, lockers and card readers.", 6f);
                    break;

                case Step.Gallery:
                    SetCard("FABRICATION GALLERY", "Everything on display was built aboard, from first principles");
                    AddTask("", "Browse the exhibits");
                    AddTask("", "Report to the drill targets at the far end");
                    Say("Sidearm recovered, quarters unsealed. Walk the fabrication gallery on your way to the drill targets.", 5.5f);
                    break;

                case Step.Drill:
                    SetCard("COMBAT DRILL", "The targets are dormant. They won't fight back");
                    m_Fire = AddTask(Key("Player/Fire", "LMB"), "Fire");
                    m_Aim = AddTask(Key("Player/Aim", "RMB"), "Aim down the sights");
                    AddTask("", "Take down the armoured target");
                    Say("Live-fire drill. The targets are dormant: aim down the sights and open up on the armoured one.", 5.5f);
                    break;

                case Step.CoreBust:
                    SetCard("CORE EXPOSED", "Its core is open until you take it");
                    AddTask(Key("Player/Interact", "E"), "Get close and Core Bust it");
                    Say("Plating's gone and its core is exposed. Get in close and rip it out.", 4.5f);
                    break;

                case Step.Disassembler:
                    SetCard("DISASSEMBLER", "Three cores banked: the hip gun is charged");
                    AddTask(Key("Player/Disassembler", "F"), "Fire the Disassembler at the Elite");
                    Say("Disassembler charged. Elites shrug off small arms. Its shock forces their chest hatch open, armour and all.", 6f);
                    break;

                case Step.EliteBust:
                    SetCard("HATCH OPEN", "In the field it seals again in seconds");
                    AddTask(Key("Player/Interact", "E"), "Core Bust the Elite through its hatch");
                    Say("Hatch is open. Out there it slams shut in seconds. Go!", 4f);
                    break;

                case Step.Clearance:
                    if (Terminal) Terminal.Arm();
                    SetCard("SECURITY CLEARANCE", "Your keycard is waiting by the exit");
                    AddTask(Key("Player/Interact", "E"), "Collect your keycard from the terminal");
                    Say("Drill complete. Your officer clearance is waiting at the terminal beside the exit.", 5f);
                    break;

                case Step.Keycard:
                    SetCard("KEYCARDS", "Keycards open the ship's security doors");
                    AddTask(Key("Player/Interact", "E"), "Tap the BLACK KEYCARD on the door's reader");
                    Say("Tap a keycard on a door's reader to open it. Black clearance opens this wing and the Workshop.", 6f);
                    Say("Every other keycard is held by a security terminal. Expect resistance.", 4.5f);
                    break;

                case Step.Complete:
                    SetCard("TRAINING COMPLETE", "Head for the Workshop");
                    AddTask("", "Recover the keycards. Reach the core vault");
                    Say("Good luck, Officer.", 3f);
                    break;
            }
        }

        // ------------------------------------------------------------------ events

        void OnWeaponTaken()
        {
            if (QuartersDoor) QuartersDoor.Unlock();
            // Taken mid-stretch, the stretch finishes first and then skips straight to the gallery.
            if (Current == Step.ArmUp) GoTo(Step.Gallery);
            else Interject(("Sidearm recovered. Quarters unsealed.", 3f));
        }

        void OnWeaponAdded(WeaponController weapon, int slot)
        {
            if (weapon) weapon.OnShootProcessed += () => m_Fired = true;
        }

        void OnArmouredHit(float damage, GameObject source)
        {
            if (m_ArmourHinted || Armoured.IsVulnerable) return;
            m_ArmourHinted = true;
            Interject(("Its plating is soaking up your shots. Keep pouring fire on. It'll crack.", 4.5f));
        }

        void OnArmourBroken()
        {
            // Exposed for good: stray fire mustn't kill it before the player gets to take its core.
            Armoured.Health.Invincible = true;
            if (Current <= Step.Drill) GoTo(Step.CoreBust);
        }

        void OnExecuted(CoreExecutionTarget target)
        {
            if (target == Armoured && !m_ArmouredDone)
            {
                m_ArmouredDone = true;
                GoTo(Step.Disassembler);
                Interject(($"Core absorbed: +{Mathf.RoundToInt(target.HealthReward)} health. Core Busts are how you heal out here.", 5f),
                    ("Spent bodies overload. Step clear before they blow.", 3.5f));
            }
            else if (target == Elite && !m_EliteDone)
            {
                m_EliteDone = true;
                GoTo(Step.Clearance);
                Interject(($"Elite core absorbed: +{Mathf.RoundToInt(target.HealthReward)} health.", 3f));
            }
        }

        void OnDisassemblerFired()
        {
            if (Current == Step.Disassembler) m_DisassemblerFiredAt = Time.time;
        }

        void OnKeycardTaken()
        {
            if (Current < Step.Keycard) GoTo(Step.Keycard);
        }

        /// <summary>
        /// Ends the tutorial at once (the room-skip hotkeys): eyes open and the player free to move, the sidearm handed
        /// over, the quarters and the wing's exit unsealed, and the card and ship's chatter cleared.
        /// </summary>
        public void Skip()
        {
            if (!IsActive || Current == Step.Complete) return;
            EyesClosed = 0f;
            if (m_Character) m_Character.enabled = true;
            if (Pod && !Pod.IsOpen) Pod.Open(true);

            var user = m_Character ? m_Character.GetComponent<KeycardInteractor>() : null;
            if (Locker && !Locker.IsTaken && user) Locker.Interact(user);
            if (m_Weapons)
            {
                foreach (var weapon in m_HeldBackWeapons)
                    if (weapon && !m_Weapons.HasWeapon(weapon)) m_Weapons.AddWeapon(weapon);
                if (!m_Weapons.GetActiveWeapon()) m_Weapons.SwitchWeapon(true);
            }
            if (QuartersDoor) QuartersDoor.Unlock();
            if (ExitDoor) ExitDoor.Unlock();

            m_Lines.Clear();
            Transmission = null;
            if (m_Voice) m_Voice.Stop();
            Current = Step.Complete;
            m_StepTime = Time.time;
            ApplyReveals();
            HideCard();
        }

        // ------------------------------------------------------------------ card and transmissions

        void SetCard(string title, string subtitle)
        {
            m_Tasks.Clear();
            CardTitle = title;
            CardSubtitle = subtitle;
            CardVisible = true;
            CardVersion++;
        }

        void HideCard()
        {
            CardVisible = false;
            CardVersion++;
        }

        Task AddTask(string key, string text)
        {
            var task = new Task { Key = key, Text = text };
            m_Tasks.Add(task);
            CardVersion++;
            return task;
        }

        void Tick(Task task, bool done)
        {
            if (task == null || task.Done || !done) return;
            task.Done = true;
            CardVersion++;
            Play(TaskDoneSfx);
        }

        bool AllDone()
        {
            foreach (var task in m_Tasks)
                if (!task.Done) return false;
            return true;
        }

        /// <summary>Queues a line from ship systems; each holds the subtitle for its seconds.</summary>
        public void Say(string text, float seconds, AudioClip voice = null) => m_Lines.Add((text, seconds, voice));

        /// <summary>Puts lines on air now, ahead of anything queued (the line on air is cut).</summary>
        void Interject(params (string text, float seconds)[] lines)
        {
            int at = 0;
            while (at < m_Lines.Count && m_Lines[at].voice) at++;
            foreach (var (text, seconds) in lines) m_Lines.Insert(at++, (text, seconds, null));
            if (!m_OnAirVoiced) Transmission = null;
        }

        void UpdateTransmission()
        {
            if (Transmission != null && Time.time - TransmissionStart < TransmissionDuration) return;
            m_OnAirVoiced = false;
            if (m_Lines.Count == 0)
            {
                Transmission = null;
                return;
            }
            var (text, seconds, voice) = m_Lines[0];
            m_Lines.RemoveAt(0);
            Transmission = text;
            TransmissionStart = Time.time;
            TransmissionDuration = seconds;
            Play(TransmissionSfx);
            if (voice && m_Voice)
            {
                // The clip opens on silence under the chirp; the next line may start in its reverb tail.
                m_OnAirVoiced = true;
                TransmissionDuration = Mathf.Max(voice.length - .4f, 1f);
                m_Voice.clip = voice;
                m_Voice.volume = VoiceVolume;
                m_Voice.Play();
            }
        }

        // The game pauses through Time.timeScale, which audio ignores: hold the voice with the subtitles.
        void HoldVoiceWhilePaused()
        {
            if (!m_Voice) return;
            bool paused = Time.timeScale == 0f;
            if (paused && m_Voice.isPlaying)
            {
                m_Voice.Pause();
                m_VoicePaused = true;
            }
            else if (!paused && m_VoicePaused)
            {
                m_Voice.UnPause();
                m_VoicePaused = false;
            }
        }

        void ApplyReveals()
        {
            if (Reveals == null) return;
            foreach (var reveal in Reveals)
            {
                if (reveal?.Objects == null) continue;
                bool show = Current >= reveal.From;
                foreach (var go in reveal.Objects)
                    if (go && go.activeSelf != show) go.SetActive(show);
            }
        }

        void Play(AudioClip clip)
        {
            if (clip && m_Audio) m_Audio.PlayOneShot(clip, SfxVolume);
        }

        // ------------------------------------------------------------------ key names (follow rebinding)

        static string Key(string actionName, string fallback, bool fallbackOnly = false)
        {
            if (fallbackOnly) return fallback;
            var action = InputSystem.actions != null ? InputSystem.actions.FindAction(actionName) : null;
            if (action == null) return fallback;
            string text = action.GetBindingDisplayString(InputBinding.MaskByGroup("Keyboard&Mouse"));
            return string.IsNullOrEmpty(text) ? fallback : Tidy(text);
        }

        // The first keyboard binding of each part of the Move composite, in W A S D order.
        static string MoveKeys()
        {
            var action = InputSystem.actions != null ? InputSystem.actions.FindAction("Player/Move") : null;
            if (action == null) return "W A S D";
            string[] order = { "up", "left", "down", "right" };
            var keys = new string[order.Length];
            var bindings = action.bindings;
            for (int i = 0; i < bindings.Count; i++)
            {
                var binding = bindings[i];
                if (!binding.isPartOfComposite || !binding.path.StartsWith("<Keyboard>")) continue;
                int part = Array.IndexOf(order, binding.name.ToLowerInvariant());
                if (part < 0 || keys[part] != null) continue;
                keys[part] = Tidy(action.GetBindingDisplayString(i));
            }
            for (int i = 0; i < keys.Length; i++)
                if (string.IsNullOrEmpty(keys[i])) return "W A S D";
            return string.Join(" ", keys);
        }

        static string Tidy(string key)
        {
            // The Interact action holds; its display name says so, but the tutorial words the hold itself.
            if (key.StartsWith("Hold ")) key = key.Substring(5);
            key = key.Replace("Left ", "").Replace("Right ", "R ").Replace("Control", "Ctrl");
            return key.ToUpperInvariant();
        }
    }
